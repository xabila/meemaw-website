window.buildAppStoreUrl = function (baseUrl, campaign) {
    try {
        var u = new URL(baseUrl);
        if (window.APPLE_PROVIDER_TOKEN) {
            u.searchParams.set("pt", window.APPLE_PROVIDER_TOKEN);
        }
        if (campaign) {
            u.searchParams.set("ct", campaign);
        }
        u.searchParams.set("mt", "8");
        return u.toString();
    } catch (e) {
        return baseUrl;
    }
};

